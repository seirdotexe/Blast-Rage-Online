import { randomBytes, scrypt, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';

const scryptAsync: any = promisify(scrypt);

/**
 * Hashes a plaintext password using scrypt
 * @param password - The plaintext password to hash
 * @returns A promise resolving to the salted password hash
 */
export const hash = async (password: string): Promise<string> => {
  const salt: string = randomBytes(8).toString('hex');
  const derivedKey = await scryptAsync(password, salt, 64);

  return `${salt}:${derivedKey.toString('hex')}`;
};

/**
 * Verifies a plaintext password against a previously generated password hash
 * @param password - The plaintext password to verify
 * @param storedHash - The hash previously generated by {@link hash}
 * @returns Whether the password matches the stored hash
 */
export const verify = async (password: string, storedHash: string): Promise<boolean> => {
  const [salt, key] = storedHash.split(':');
  const derivedKey = await scryptAsync(password, salt, 64);

  return timingSafeEqual(Buffer.from(key as string, 'hex'), derivedKey);
};